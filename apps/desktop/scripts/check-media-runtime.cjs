// Built worker + real local decoding acceptance. No microphone, provider key,
// account, download or production user data. Supply your installed FFmpeg path.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { execFileSync } = require('node:child_process')
const { buildSync } = require('esbuild')
const { createCanvas } = require('@napi-rs/canvas')
const app = path.resolve(__dirname, '..')
const ffmpeg = process.env.ODDBRAIN_TEST_FFMPEG
if (!ffmpeg) throw Error('Set ODDBRAIN_TEST_FFMPEG to your installed FFmpeg executable; no binary is downloaded by this check.')
const harness = path.join(app, 'out/main/media-runtime-check.cjs')
buildSync({ stdin: { contents: "export {createMediaService} from './src/main/media/service'; export {createZip} from './src/main/vault/zip'", resolveDir: app, loader: 'ts' }, outfile: harness, platform: 'node', format: 'cjs', bundle: true, packages: 'external' })
const { createMediaService, createZip } = require(harness)
;(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'oddbrain-acceptance-'))
  try {
    const service = createMediaService({ file: path.join(root, 'media.json'), access: () => ({ permissions: { local: true, cloud: {} }, external: false, key: () => '', customBaseUrl: '' }) })
    service.update({ ffmpeg }, true)
    const decode = (name, bytes, mime = '') => service.decode(1, { name, bytes, mime, route: 'local' })
    assert.match((await decode('notes.txt', Buffer.from('Built worker text.'))).text, /Built worker text/)
    const office = createZip([{ name: 'word/document.xml', content: '<w:document xmlns:w="w"><w:p><w:r><w:t>Worker Office words</w:t></w:r></w:p></w:document>' }])
    assert.match((await decode('notes.docx', office)).text, /Worker Office words/)
    const png = createCanvas(4, 4).toBuffer('image/png')
    const image = await decode('image.png', png); assert.equal(image.ok, true, image.error); assert.equal(image.images[0].mime, 'image/jpeg')
    const protectedFile = await decode('protected.docx', Buffer.from('d0cf11e0a1b11ae10000', 'hex'))
    assert.equal(protectedFile.ok, false); assert.equal(protectedFile.fallbackAllowed, false)
    const video = path.join(root, 'short.mp4')
    execFileSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'color=red:s=160x120:r=10', '-t', '2', '-c:v', 'mpeg4', '-y', video], { timeout: 15000 })
    const original = await fs.readFile(video)
    const movie = await decode('short.mp4', original, 'video/mp4')
    assert.equal(movie.ok, true, movie.error); assert.equal(movie.images.length, 1); assert.match(movie.disclosure, /Audio was NOT transcribed/)
    assert.deepEqual(await fs.readFile(video), original)
    const wav = path.join(root, 'sound.wav')
    execFileSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440', '-t', '1', '-y', wav], { timeout: 15000 })
    if (process.platform !== 'win32') {
      const audio = await decode('sound.wav', await fs.readFile(wav), 'audio/wav')
      assert.equal(audio.ok, false); assert.match(audio.error, /Windows/)
    }
    const pending = decode('cancel.txt', Buffer.from('cancelled worker'))
    service.cancel(1); assert.match((await pending).error, /Cancelled/)
    console.log('PASS: built worker text/Office/image decode, encryption refusal, short-video frame, unchanged originals, cancellation; non-Windows speech reports its limitation. No provider or microphone acceptance claimed.')
  } finally { await fs.rm(root, { recursive: true, force: true }); await fs.rm(harness, { force: true }) }
})().catch(error => { console.error(error); process.exitCode = 1 })
