const COUNTER = '<!doctype html><html><head><title>Counter</title></head><body><button id="counter" onclick="this.textContent=Number(this.textContent)+1">0</button></body></html>'
async function mockOllama(page, options = {}) {
  const requests = []
  await page.route('**/api/ollama/**', async route => {
    const endpoint = new URL(route.request().url()).pathname
    if (endpoint.endsWith('/tags')) return route.fulfill({ json: { models: [{ name: 'qwen2.5:3b', details: { parameter_size: '3B' } }, { name: 'vision-test:4b', details: { parameter_size: '4B' } }] } })
    if (endpoint.endsWith('/show')) return route.fulfill({ json: { capabilities: route.request().postDataJSON().model === 'vision-test:4b' ? ['completion', 'vision', 'thinking'] : ['completion'] } })
    if (endpoint.endsWith('/chat')) {
      const payload = route.request().postDataJSON()
      requests.push(payload)
      if (options.delay) await new Promise(resolve => setTimeout(resolve, options.delay))
      const content = options.content || (payload.messages.at(-1).content.toLowerCase().includes('build') ? `Here is your app.\n\n\`\`\`html\n${COUNTER}\n\`\`\`` : 'Hello, Friend. This is a synthetic test reply.')
      const records = [{ message: { content, ...(payload.think ? { thinking: 'Synthetic model thinking output.' } : {}) } }, { done: true }]
      try { await route.fulfill({ contentType: 'application/x-ndjson', body: records.map(record => JSON.stringify(record)).join('\n') + '\n' }) } catch { /* Request may have been explicitly stopped. */ }
    } else await route.abort()
  })
  return requests
}
async function open(page, options) {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const requests = await mockOllama(page, options)
  await page.clock.setFixedTime(new Date('2026-10-10T13:00:00Z'))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Evening, Friend' })).toBeVisible()
  await expect(page.locator('.center')).toHaveAttribute('data-model-ready', 'true')
  return { requests, errors }
}
