const { chromium } = require('playwright-core')
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path')
const { openSettingsSection } = require('./settings-navigation.cjs')
const base = process.env.ODDBRAIN_UI_URL || 'http://127.0.0.1:5174/'
const output = path.resolve(process.env.ODDBRAIN_QA_DIR || 'qa-ui')
;(async () => {
  const browser = await chromium.launch(process.env.ODDBRAIN_BROWSER_OPTIONS ? JSON.parse(fs.readFileSync(process.env.ODDBRAIN_BROWSER_OPTIONS, 'utf8')) : {})
  const report = { checks: [], errors: [] }; fs.mkdirSync(output, { recursive: true })
  try {
    const p = await browser.newPage({ viewport: { width: 1536, height: 864 }, reducedMotion: 'reduce' })
    p.on('pageerror', error => report.errors.push(error.message))
    await p.goto(base); await p.locator('.ob-launch').waitFor({ state: 'hidden' })
    assert.equal(await p.locator('html').getAttribute('data-ob-layout'), 'twopane')
    await p.keyboard.press('Control+,'); await p.locator('.ob-settings-view').waitFor()
    assert.match(await p.locator('.ob-preset-row[aria-pressed=true]').innerText(), /Ink & Sketchbook/)
    assert.equal(await p.locator('.ob-settings-area-description').count(), 8)
    await p.getByRole('button', { name: 'Brain & motion', exact: true }).click()
    for (const [role, scene] of Object.entries({ idle:'sketch', thinking:'idea', working:'architect', waiting:'unwind', done:'sparkle', searching:'lens-inspector', making:'forge', resting:'nap' })) {
      assert.equal(await p.locator('#ob-role-' + role).inputValue(), scene)
    }
    report.checks.push('Fresh Ink & Sketchbook appearance and all eight behaviour roles match, with existing saved-choice tests retained')
    await openSettingsSection(p, 'Connectors')
    assert.equal(await p.locator('.ob-settings-navigation .ob-settings-subsections button').count(), 4)
    assert.equal(await p.locator('.ob-settings-content .ob-settings-subsections').count(), 0)
    await p.getByRole('button', { name:'Engine plugin store', exact:true }).click()
    assert.equal(await p.locator('.ob-settings-content h1').innerText(), 'Plugins')
    await openSettingsSection(p, 'Connectors'); await p.getByRole('button', { name:'Browse skills', exact:true }).click()
    assert.equal(await p.locator('.ob-settings-content h1').innerText(), 'Skills')
    await p.getByLabel('Skill source', { exact:true }).selectOption('agy')
    await p.getByText('Official source: antigravity-plugins-official', { exact:true }).waitFor()
    assert(await p.getByRole('button', { name:'Browse / refresh', exact:true }).isDisabled())
    await p.screenshot({ path:path.join(output,'skills-agy-store.png'), animations:'disabled' })
    await p.getByLabel('Skill source', { exact:true }).selectOption('claude-code')
    await p.getByRole('button', { name:'Anthropic · Official marketplace', exact:true }).click()
    assert.equal(await p.getByLabel('Marketplace repository', { exact:true }).inputValue(),'anthropics/claude-plugins-official')
    await p.getByLabel('Skill source', { exact:true }).selectOption('shared')
    assert.equal(await p.getByRole('button', { name:'Install the docx skill', exact:true }).count(),1)
    await openSettingsSection(p, 'Connectors')
    await p.getByLabel('Connector source', { exact:true }).selectOption('agy')
    await p.getByLabel('Connector source', { exact:true }).scrollIntoViewIfNeeded()
    await p.getByText('Official source: antigravity-plugins-official', { exact:true }).waitFor()
    await p.getByText('Official source: antigravity-plugins-official', { exact:true }).evaluate(element => element.scrollIntoView({ block:'center' }))
    await p.screenshot({ path:path.join(output,'connectors-agy-store.png'), animations:'disabled' })
    await p.setViewportSize({ width:940, height:620 })
    assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await p.getByLabel('Connector source', { exact:true }).selectOption('shared')
    await p.setViewportSize({ width:1536, height:864 })
    report.checks.push('Skills and Connectors offer both engine catalogs, preserve shared controls and refuse native/network actions in the preview')
    await openSettingsSection(p, 'Connectors'); await p.getByRole('button', { name:'API providers', exact:true }).click()
    assert.equal(await p.locator('.ob-settings-content h1').innerText(), 'Models & API keys')
    await openSettingsSection(p, 'Connectors')
    await p.getByText('How to connect it', { exact:true }).click()
    await p.getByRole('button', { name:'Save extension to Downloads', exact:true }).click()
    assert.match(await p.locator('.ob-extension-install [role=status]').innerText(), /No files were created/)
    await p.locator('.ob-extension-install').scrollIntoViewIfNeeded()
    await p.screenshot({ path:path.join(output,'settings-extension-desktop.png'), animations:'disabled' })
    await p.setViewportSize({ width:940, height:620 })
    await p.screenshot({ path:path.join(output,'settings-extension-small.png'), animations:'disabled' })
    assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await p.getByRole('button', { name:'Browser capture permissions', exact:true }).click()
    assert.equal(await p.locator('.ob-settings-content h1').innerText(), 'Agent access')
    report.checks.push('Vertical Settings pages, working skills/plugins/API shortcuts, preview refusal, installation guide and capture-permission shortcut; 1536×864 and 940×620')
    assert.deepEqual(report.errors, [])
  } catch (error) { report.failure = error.stack; process.exitCode = 1 }
  finally { fs.writeFileSync(path.join(output,'settings-results.json'),JSON.stringify(report,null,2)); console.log(JSON.stringify(report,null,2)); await browser.close() }
})()
