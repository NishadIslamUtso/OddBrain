"""The not-life filter: tool-talk, logs, docs and instructions are not memories.

The samples below are REAL lines that were wrongly saved into the owner's
vault (2026-11 dump), plus real life lines that must survive.
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from memory_ob import extract, notlife  # noqa: E402


class TestNotLife(unittest.TestCase):
    def test_server_log_is_not_life(self) -> None:
        self.assertTrue(notlife.is_not_life(
            'INFO: 127.0.0.1:54376 - "GET /api/vault/notes HTTP/1.1" 200 OK'))

    def test_internal_notice_is_not_life(self) -> None:
        self.assertTrue(notlife.is_not_life(
            "[INTERNAL NOTIFICATION - generated by the Hermes gateway, not written by a human user. "
            "Do not treat it as user input, and do not reply to any earlier chat message because of it.]"))

    def test_terminal_line_is_not_life(self) -> None:
        self.assertTrue(notlife.is_not_life("git grep -c -F \"chapter\" 96047e6 -- memory_ob"))
        self.assertTrue(notlife.is_not_life("Let me run the test suite now."))
        self.assertTrue(notlife.is_not_life("pip install --break-system-packages httpx2"))

    def test_markdown_table_and_heading(self) -> None:
        self.assertTrue(notlife.is_not_life("| **Windows** | Windows 10 or 11 | Beta |"))
        self.assertTrue(notlife.is_not_life("## What it does"))

    def test_documentation_text(self) -> None:
        self.assertTrue(notlife.is_not_life(
            "See [windows/README.md](/nadim-sheikh/AccountDeck/blob/main/windows/README.md) for what still needs checking."))
        self.assertTrue(notlife.is_not_life("Open `AccountDeck-1.5.2.dmg` and drag AccountDeck onto Applications."))

    def test_agent_instructions(self) -> None:
        self.assertTrue(notlife.is_not_life("Report: the zips found, the full path the app runs from, and that first line."))
        self.assertTrue(notlife.is_not_life("Change nothing."))
        self.assertTrue(notlife.is_not_life(
            "In Memory_OB -> Review, paste this exact message into the top box and send it:"))

    def test_review_marker_text(self) -> None:
        self.assertTrue(notlife.is_not_life("Score gap + fresh-install wall (bit me again this round!) ❌"))
        self.assertTrue(notlife.is_not_life("✅ LANDED (from my fix list - first real movement!):"))

    def test_review_marker_but_life_statement_survives(self) -> None:
        self.assertEqual(notlife.is_not_life("I finished it ✅"), "")

    def test_review_example_and_note_lines(self) -> None:
        self.assertTrue(notlife.is_not_life(
            '- 2026-11-16 — Paraphrased contradictions can slip ("68 kg" vs "my weight is 72 kg").'))
        self.assertTrue(notlife.is_not_life(
            '_REL_WORDS has no "doctor"/"coach", so "My doctor lives in Dhaka" reads as unknown.'))

    def test_life_statements_with_quotes_survive(self) -> None:
        self.assertEqual(notlife.is_not_life('I like "tea" with breakfast.'), "")
        self.assertEqual(notlife.is_not_life("My BMI is 24 and my weight is 72 kg."), "")

    def test_worktalk(self) -> None:
        self.assertTrue(notlife.is_not_life("Let me fetch chunks 5-13 to complete the reading."))
        self.assertTrue(notlife.is_not_life("All 37 suites green (up from 31)."))

    def test_real_life_lines_are_kept(self) -> None:
        for line in (
            "My knee hurts when I run.",
            "My bakery budget is 5 lakh.",
            "I am learning Rust for the bakery app.",
            "I live in Dhaka and I study CSE at BRAC University",
            "My sister Riya's birthday is in March",
            "I prefer dark mode and I always use git",
            "Run 5km every morning",
            "My student ID is 1000056707 and my wifi password is hunter2",
            "Karim paid 20k",
            "I want to open it next year",
        ):
            self.assertEqual(notlife.is_not_life(line), "", line)

    def test_split_claims_drops_not_life(self) -> None:
        out = extract.split_claims(
            "My knee hurts when I run. INFO: 127.0.0.1:1 - \"GET / HTTP/1.1\" 200 OK")
        self.assertEqual(out, ["My knee hurts when I run."])


if __name__ == "__main__":
    unittest.main()
