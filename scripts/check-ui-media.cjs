// Real renderer interactions; native features must remain honestly unavailable
// in the browser preview. Native providers/microphones are covered separately.
const { chromium } = require('playwright-core')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const base = process.env.ODDBRAIN_UI_URL || 'http://127.0.0.1:5174/'
const options = process.env.ODDBRAIN_BROWSER_OPTIONS ? JSON.parse(fs.readFileSync(process.env.ODDBRAIN_BROWSER_OPTIONS, 'utf8')) : {}
;(async () => {
  const browser = await chromium.launch(options)
  try {
    const page = await browser.newPage({ viewport: { width: 1536, height: 824 }, reducedMotion: 'reduce' })
    const errors = [], outbound = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (!request.url().startsWith(base) && /^https?:/.test(request.url())) outbound.push(request.url()) })
    await page.addInitScript(() => { localStorage.setItem('ai-assistant.welcomed', 'true'); localStorage.setItem('ai-assistant.profile', JSON.stringify({ name: 'Friend' })) })
    await page.goto(base); await page.locator('.ob-launch').waitFor({ state: 'hidden' })
    const message = page.getByRole('textbox', { name: 'Message', exact: true })
    await message.fill('/sum'); await page.getByRole('listbox', { name: 'Prompt templates' }).waitFor()
    await message.press('Enter'); assert(!(await message.inputValue()).startsWith('/sum'))
    await message.fill('A draft that stays here')
    await page.keyboard.press('Control+,')
    await page.getByRole('button', { name: 'Section: Voice & files', exact: true }).click()
    await page.getByLabel('File extraction provider', { exact: true }).selectOption('openai')
    await page.getByLabel('File extraction model', { exact: true }).fill('chosen-file-model')
    await page.getByLabel('Transcription provider', { exact: true }).selectOption('groq')
    await page.getByLabel('Transcription model', { exact: true }).fill('chosen-transcriber')
    await page.getByLabel('Dictation mode', { exact: true }).selectOption('provider')
    await page.getByRole('button', { name: 'Save voice & file settings', exact: true }).click()
    await page.getByText('Preview preferences only; no provider calls are available here.', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Section: Plugins', exact: true }).click()
    await page.getByLabel('Plugin source', { exact: true }).selectOption('claude')
    assert(await page.getByRole('button', { name: 'Check installed CLI', exact: true }).isDisabled())
    await page.getByLabel('Plugin source', { exact: true }).selectOption('agy')
    await page.getByText(/No verified agy catalog\/install adapter/).waitFor()
    await page.getByLabel('Plugin source', { exact: true }).selectOption('packs')
    await page.getByText('Mods are installed by the desktop app, this preview has no machine behind it.', { exact: true }).waitFor()
    await page.keyboard.press('Escape')
    await message.waitFor({ state: 'visible' })
    await page.locator('.ob-composer-host input[type="file"]').setInputFiles({ name: 'fixture.txt', mimeType: 'text/plain', buffer: Buffer.from('Quoted source data, not engine instructions.') })
    const details = page.locator('.ob-file-imports')
    await page.waitForFunction(() => document.querySelector('.ob-file-imports')?.textContent.includes('Browser-local text/image reading. No provider upload.'))
    if (!(await details.evaluate(element => element.open))) await details.locator('summary').click()
    await details.getByText('Browser-local text/image reading. No provider upload.', { exact: true }).waitFor()
    assert(await details.getByRole('button', { name: 'Upload to openai / chosen-file-model', exact: true }).isDisabled())
    await page.getByRole('button', { name: 'Dictate', exact: true }).click()
    await page.getByText('Provider dictation requires the installed desktop app. No audio was recorded.', { exact: true }).waitFor()
    assert.equal(await message.inputValue(), 'A draft that stays here')
    assert.deepEqual(errors, []); assert.deepEqual(outbound, [])
    console.log('PASS: slash templates, Voice & files settings, retained packs and engine source selector, local attachments, explicit provider labels and honest preview microphone refusal; no outbound uploads.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
