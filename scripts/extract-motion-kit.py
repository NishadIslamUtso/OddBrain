#!/usr/bin/env python3
"""
Extract the OddBrain Motion Kit 3.0.1 from the owner's gallery HTML into the app.

Source of truth: the kit's own embedded JSON (`<script id="motion-data">`) —
76 scene SVGs + 1 utility loader, byte-exact, plus the 304-word status map and
the word→animation variant map. Re-run after replacing the kit HTML to refresh.

Inputs : $KIT_HTML (default /home/user/uploads/index.html)
Outputs: apps/03_ai-assistant/src/renderer/src/assets/motion/<id>.svg  (77 files)
         apps/03_ai-assistant/src/shared/lib/motionKitData.ts          (generated data)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "apps/03_ai-assistant"
KIT_HTML = Path(sys.argv[1] if len(sys.argv) > 1 else "/home/user/uploads/index.html")

html = KIT_HTML.read_text(encoding="utf-8")
m = re.search(r'<script type="application/json" id="motion-data">', html)
if not m:
    sys.exit("motion-data script not found — is this the kit 3.0.1 gallery?")
end = html.index("</script>", m.end())
data = json.loads(html[m.end():end].strip())

manifest = data["manifest"]
if manifest["version"] != "3.0.1":
    sys.exit(f"unexpected kit version {manifest['version']} — the brief pins 3.0.1 (the corrected forge)")
motions = manifest["motions"]
artwork = data["artwork"]
status_map = data["statusMap"]
variant_map = data["variantMap"]
utilities = [u for u in data.get("utilities", [])] if isinstance(data.get("utilities"), list) else []
loader_id = "loader-eye-roll"

motion_ids = [mo["id"] for mo in motions]
assert len(motions) == 76, f"expected 76 motions, got {len(motions)}"
assert len(artwork) == 77, f"expected 77 artworks (76 + loader), got {len(artwork)}"
assert loader_id in artwork, "the loader utility is missing from artwork"
assert set(status_map) == set(variant_map), "statusMap and variantMap disagree on words"
known = set(motion_ids) | {loader_id}
for word, ids in variant_map.items():
    assert set(ids) <= known, f"word {word!r} names an unknown motion: {ids}"

# ---- SVG files, byte-exact -------------------------------------------------
out_dir = APP / "src/renderer/src/assets/motion"
out_dir.mkdir(parents=True, exist_ok=True)
for old in out_dir.glob("*.svg"):
    old.unlink()
for mid, svg in artwork.items():
    assert svg.startswith("<svg"), mid
    (out_dir / f"{mid}.svg").write_text(svg, encoding="utf-8", newline="")

# ---- generated data module -------------------------------------------------
def ts_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)

lines = []
lines.append("/* eslint-disable */")
lines.append("/**")
lines.append(" * GENERATED by scripts/extract-motion-kit.py — do not edit by hand.")
lines.append(" * Source: the OddBrain Motion Kit 3.0.1 gallery JSON (76 scenes + loader,")
lines.append(" * 304 status words). The forge scene is the 3.0.1 corrected hammer.")
lines.append(" * The SVGs themselves live in src/renderer/src/assets/motion/ (byte-exact).")
lines.append(" */")
lines.append("")
lines.append(f"export const KIT_VERSION = {ts_str(manifest['version'])}")
lines.append("")
lines.append("export type MotionSpec = {")
lines.append("  id: string")
lines.append("  name: string")
lines.append("  category: string")
lines.append("  duration: number")
lines.append("  loop: boolean")
lines.append("  energy: 'low' | 'medium' | 'high'")
lines.append("  defaultWord: string")
lines.append("  words: string[]")
lines.append("}")
lines.append("")
lines.append("export const MOTIONS: MotionSpec[] = [")
for mo in motions:
    energy = mo.get("energy", "medium")
    if energy not in ("low", "medium", "high"):
        energy = "medium"
    words = ", ".join(ts_str(w) for w in mo["words"])
    lines.append("  { id: %s, name: %s, category: %s, duration: %s, loop: %s, energy: '%s', defaultWord: %s, words: [%s] }," % (
        ts_str(mo["id"]), ts_str(mo.get("name", mo["id"])), ts_str(mo.get("category", "")),
        json.dumps(mo.get("duration", 3)), "true" if mo.get("loop", True) else "false",
        energy, ts_str(mo.get("defaultWord", mo["words"][0] if mo["words"] else mo["id"])), words))
lines.append("]")
lines.append("")
lines.append(f"export const LOADER_ID = {ts_str(loader_id)}")
lines.append("/** Every artwork id shipped in assets/motion/ — 76 scenes + the loader. */")
lines.append("export const ARTWORK_IDS: readonly string[] = Object.freeze(%s)" % json.dumps(sorted(artwork)))
lines.append("")
lines.append("/** Word → the motion that owns it (the kit's statusMap, 304 words). */")
lines.append("export const STATUS_MAP: Readonly<Record<string, string>> = Object.freeze(%s);" % json.dumps(status_map, sort_keys=True, ensure_ascii=True))
lines.append("")
lines.append("/** Word → every animation that can carry it (the kit's variantMap). */")
lines.append("export const VARIANT_MAP: Readonly<Record<string, readonly string[]>> = Object.freeze(Object.fromEntries(%s));" % json.dumps(sorted(variant_map.items()), ensure_ascii=True))
lines.append("")

(APP / "src/shared/lib/motionKitData.ts").write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {len(artwork)} SVGs to {out_dir.relative_to(ROOT)}")
print(f"wrote motionKitData.ts ({len(motions)} motions, {len(status_map)} words)")
